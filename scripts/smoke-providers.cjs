// Invoked by the isolated desktop harness after installing its ephemeral vault codec.
const assert = require('node:assert/strict')
const { join } = require('node:path')
const { writeFileSync } = require('node:fs')

module.exports = async function smokeProviders({ window, waitForDOM, captureStable, output, baseUrl }) {
  const run = expression => window.webContents.executeJavaScript(expression)
  const click = async (selector,text) => {
    try { await run(`Array.from(document.querySelectorAll(${JSON.stringify(selector)})).find(el=>el.getClientRects().length && el.textContent.replace(/\\s/g,'')===${JSON.stringify(text.replace(/\s/g,''))}).click()`) }
    catch { throw new Error(`Provider smoke button missing: ${selector} / ${text}`) }
  }
  const input = (label,value) => run(`(() => {const el=document.querySelector('[aria-label=${JSON.stringify(label)}]');const proto=el.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype;Object.getOwnPropertyDescriptor(proto,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}));})()`)
  const wait = expression => waitForDOM(window,expression)
  const snapshot = () => run('window.manager.load()')
  await run(`Array.from(document.querySelectorAll('.ant-menu-item')).find(el=>el.textContent.includes('供应商与密钥')).click()`)
  await wait(`!!document.querySelector('.provider-library')`)
  console.log('smoke: provider library page loaded')
  await click('.provider-library button','添加供应商')
  await wait(`!!document.querySelector('input[aria-label="供应商名称"]')`)
  await input('供应商名称','本地模拟上游')
  await input('供应商地址',baseUrl)
  await click('.model-discovery button','从 API 获取模型')
  await wait(`document.querySelector('.model-discovery')?.textContent.includes('已获取 1 个模型')`)
  await click('.model-discovery button','全部加入')
  await run(`Array.from(document.querySelectorAll('.provider-details-form .ant-form-item')).find(el=>el.querySelector('label')?.textContent==='默认服务等级').querySelector('.ant-select-selector').dispatchEvent(new MouseEvent('mousedown',{bubbles:true}))`)
  await wait(`Array.from(document.querySelectorAll('.ant-select-item-option')).some(el=>el.getClientRects().length && el.textContent==='Fast')`)
  await click('.ant-select-item-option','Fast')
  writeFileSync(join(output,'provider-library-editor.png'),(await captureStable(window)).toPNG())
  await click('.ant-drawer-open button','保存供应商')
  await wait(`!document.querySelector('.ant-drawer-open')`)
  await wait(`!!document.querySelector('.provider-key-table')`)
  let state = await snapshot(), provider = state.providers[0]
  assert.equal(provider.defaultTier,'fast')
  assert.equal(provider.keys.length,1,'Matching existing API account is merged without exposing its key')
  assert.equal(JSON.stringify(provider).includes('fake-key-smoke-only'),false)
  console.log('smoke: provider library UI created and account key reconciled')
  await click('.provider-library button','添加密钥')
  await wait(`!!document.querySelector('input[aria-label="供应商密钥"]')`)
  await input('密钥或账号名称','备用接口密钥')
  await input('供应商密钥','fixture-provider-ui-secret')
  await run(`document.querySelector('.provider-key-form .ant-checkbox-input').click()`)
  await click('.ant-modal-footer button','保存')
  await wait(`!document.querySelector('input[aria-label="供应商密钥"]')`)
  await wait(`document.querySelector('.provider-key-table').textContent.includes('备用接口密钥')`)
  await run(`Array.from(Array.from(document.querySelectorAll('.provider-key-table tbody tr')).find(el=>el.textContent.includes('备用接口密钥')).querySelectorAll('button')).find(el=>el.textContent==='编辑').click()`)
  await wait(`!!document.querySelector('input[aria-label="供应商密钥"]')`)
  await wait(`document.querySelector('input[aria-label="供应商密钥"]')?.value==='fixture-provider-ui-secret'`)
  assert.equal(await run(`document.querySelector('input[aria-label="供应商密钥"]').type`),'text')
  await input('密钥或账号名称','项目工作密钥')
  await click('.ant-modal-footer button','保存')
  await wait(`!document.querySelector('input[aria-label="供应商密钥"]')`)
  await wait(`document.querySelector('.provider-key-table').textContent.includes('项目工作密钥')`)
  console.log('smoke: provider library UI key added and renamed')
  await run(`Array.from(Array.from(document.querySelectorAll('.provider-key-table tbody tr')).find(el=>el.textContent.includes('项目工作密钥')).querySelectorAll('button')).find(el=>el.textContent==='启用连接').click()`)
  await wait(`!!document.querySelector('input[aria-label="密钥或账号名称"]')`)
  await input('密钥或账号名称','供应商关联账号')
  await click('.ant-modal-footer button','保存')
  await wait(`!document.querySelector('input[aria-label="密钥或账号名称"]')`)
  await wait(`document.querySelector('.provider-key-table').textContent.includes('供应商关联账号')`)
  state = await snapshot(); provider = state.providers[0]
  const account = state.accounts.find(a=>a.name==='供应商关联账号')
  assert.equal(account.providerId,provider.id)
  assert.equal(account.defaultTier,'inherit')
  assert.equal(JSON.stringify(state).includes('fixture-provider-ui-secret'),false)
  assert.equal(await run(`document.body.textContent.includes('fixture-provider-ui-secret')`),false)
  await wait(`!document.querySelector('.ant-message-notice')`)
  writeFileSync(join(output,'provider-library-saved.png'),(await captureStable(window)).toPNG())
  await run('document.getElementById("api-connections-tab").click()')
  await wait(`Array.from(document.querySelectorAll('.account-card')).some(el=>el.textContent.includes('供应商关联账号'))`)
  await run(`Array.from(document.querySelectorAll('.account-card')).find(el=>el.textContent.includes('供应商关联账号')).querySelector('footer button.account-edit').click()`)
  await wait(`!!document.querySelector('.ant-drawer-open')`)
  assert.equal(await run(`!!document.querySelector('.ant-drawer-open input[type="password"]')`),false)
  assert.equal(await run(`!!document.querySelector('.connection-shared-config')`),true)
  assert.equal(await run(`document.querySelector('.connection-inherited-details').open`),false)
  assert.match(await run(`document.querySelector('.ant-drawer-open').textContent`),/继承供应商设置/)
  writeFileSync(join(output,'provider-linked-account.png'),(await captureStable(window)).toPNG())
  await run(`document.querySelector('.ant-drawer-open .ant-drawer-close').click()`)
  await wait(`!document.querySelector('.ant-drawer-open')`)
  return account.id
}
