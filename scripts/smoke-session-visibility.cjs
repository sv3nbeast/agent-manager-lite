const {app,safeStorage}=require('electron')
const {mkdirSync,writeFileSync,readFileSync,rmSync,existsSync}=require('node:fs')
const {join,resolve}=require('node:path')
const {randomUUID}=require('node:crypto')
const {DatabaseSync}=require('node:sqlite')
const assert=require('node:assert/strict')
const directory=process.env.CML_TEST_DATA_DIR
assert.ok(directory)
require('./test-vault.cjs').installTestVault(safeStorage)
const home=join(directory,'clients','default'),id=randomUUID(),rolloutRelative='sessions/2026/10/02/rollout-visibility.jsonl',rollout=join(home,rolloutRelative)
mkdirSync(join(home,'sessions/2026/10/02'),{recursive:true})
writeFileSync(join(home,'config.toml'),'model_provider = "relay"\n')
writeFileSync(rollout,JSON.stringify({type:'session_meta',payload:{id,model_provider:'openai'}})+'\n')
const db=new DatabaseSync(join(home,'state_5.sqlite'))
db.exec('CREATE TABLE threads (id TEXT PRIMARY KEY, model_provider TEXT, has_user_event INTEGER, first_user_message TEXT, thread_source TEXT, preview TEXT, archived INTEGER, rollout_path TEXT)')
db.prepare('INSERT INTO threads VALUES (?,?,?,?,?,?,?,?)').run(id,'openai',0,'visibility smoke','','',0,rolloutRelative)
db.close()
const timer=setTimeout(()=>{console.error('session visibility smoke timed out');app.exit(1)},30000)
app.on('browser-window-created',(_event,window)=>window.webContents.once('did-finish-load',async()=>{
  try{
    const run=expression=>window.webContents.executeJavaScript(expression)
    const list=await run('window.manager.listSessionVisibilityRepairInstances()'),target=list.instances.find(value=>value.directory.includes("clients/default"));assert.ok(target)
    const preview=await run(`window.manager.previewSessionVisibilityRepair(${JSON.stringify({targetIds:[target.id],sessionIds:[id]})})`);assert.equal(preview.updatedSqliteRowCount,1);assert.equal(preview.changedRolloutFileCount,1)
    const result=await run(`window.manager.applySessionVisibilityRepair(${JSON.stringify({ticket:preview.ticket,confirmed:true})})`);assert.equal(result.updatedSqliteRowCount,1);assert.equal(result.backupDirs.length,1);assert.ok(existsSync(join(result.backupDirs[0],'manifest.json')))
    const verify=new DatabaseSync(join(home,'state_5.sqlite'));const row=verify.prepare('SELECT model_provider,has_user_event,thread_source,preview FROM threads WHERE id=?').get(id);verify.close();assert.equal(row.model_provider,'relay');assert.equal(row.has_user_event,1);assert.equal(row.thread_source,'user');assert.equal(row.preview,'visibility smoke');assert.equal(JSON.parse(readFileSync(rollout,'utf8')).payload.model_provider,'relay')
    console.log('Session visibility smoke passed: real Electron IPC preview/apply, dynamic SQLite metadata repair, referenced rollout rewrite and backup manifest.')
    clearTimeout(timer);window.destroy();app.exit(0)
  }catch(error){console.error(error);clearTimeout(timer);app.exit(1)}
}))
require('../out/main/index.js')
